import { access, cp, rm, writeFile } from 'node:fs/promises';
import { constants } from 'node:fs';
import { resolve } from 'node:path';

const source = resolve('apps/site/dist');
const destination = resolve('dist');
const marker = resolve(destination, '.sites-build-output');

const exists = async (path) => access(path, constants.F_OK).then(() => true).catch(() => false);

if (await exists(destination) && !(await exists(marker))) {
  throw new Error('Refusing to replace an unmarked root dist directory.');
}

await rm(destination, { recursive: true, force: true });
await cp(source, destination, { recursive: true });
await writeFile(marker, 'Generated by pnpm sites:build. Do not edit manually.\n', 'utf8');
