export function getMessages(locale: SiteLocale) {
  return messages[locale];
}

export function getLocalizedExercise(exercise: Exercise, locale: SiteLocale) {
  const translation = getExerciseTranslation(exercise.id, locale);
  if (!translation) throw new Error(`Missing ${locale} translation for ${exercise.id}.`);
  return translation;
}

export function formatMessage(template: string, values: Record<string, string | number>) {
  return template.replace(/\{(\w+)\}/g, (_, key: string) => String(values[key] ?? ''));
}

export function formatResultCount(locale: SiteLocale, visible: number, total: number) {
  if (locale === 'zh-CN') return visible === total ? `显示全部 ${visible} 个动作` : `找到 ${visible} 个动作`;
  return visible === total ? `Showing all ${visible} exercises` : `${visible} exercise${visible === 1 ? '' : 's'} found`;
}
